#!/usr/bin/env python3
"""
Renders the app's one typeface into src/font_data.h.

The app has no text library and no font file on the device: every glyph it can
draw is in this table. ASCII and Latin-1 at one size, as 8-bit coverage, which
draw.c blends onto the framebuffer. The generated header is checked in, so
building the app does not need Python; run this only to change the face or the
size:

    pip install pillow
    python3 tools/genfont.py

The face is DejaVu Sans (https://dejavu-fonts.github.io), which may be embedded
and redistributed in this form.
"""

import os
import sys

from PIL import Image, ImageDraw, ImageFont

FACE = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
SIZE = 24
CODES = list(range(32, 127)) + list(range(160, 256))
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src", "font_data.h")


def main():
    if not os.path.exists(FACE):
        sys.exit("font not found: %s" % FACE)
    font = ImageFont.truetype(FACE, SIZE)
    ascent, descent = font.getmetrics()

    glyphs = []
    data = bytearray()
    for code in CODES:
        ch = chr(code)
        advance = int(round(font.getlength(ch)))
        box = font.getbbox(ch)  # left, top, right, bottom from the pen, top of the line at 0
        w, h = max(0, box[2] - box[0]), max(0, box[3] - box[1])
        if w == 0 or h == 0:
            glyphs.append((code, len(data), 0, 0, 0, 0, advance))
            continue
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-box[0], -box[1]), ch, font=font, fill=255)
        glyphs.append((code, len(data), w, h, box[0], box[1], advance))
        data += img.tobytes()

    with open(OUT, "w") as f:
        f.write("// GENERATED by tools/genfont.py from DejaVu Sans. Do not edit by hand.\n\n")
        f.write("#ifndef FONT_DATA_H\n#define FONT_DATA_H\n\n#include <stdint.h>\n\n")
        f.write("#define FONT_LINE_HEIGHT %d\n#define FONT_ASCENT %d\n\n" % (ascent + descent, ascent))
        f.write("typedef struct {\n\tuint16_t code;\n\tuint32_t offset; // into font_coverage\n"
                "\tuint8_t w, h;\n\tint8_t left, top; // from the pen, the top of the line at 0\n\tuint8_t advance;\n} font_glyph_t;\n\n")
        f.write("static const font_glyph_t font_glyphs[] = {\n")
        for g in glyphs:
            f.write("\t{%d, %d, %d, %d, %d, %d, %d},\n" % g)
        f.write("};\n\n#define FONT_GLYPH_COUNT %d\n\n" % len(glyphs))
        f.write("static const uint8_t font_coverage[] = {\n")
        for i in range(0, len(data), 20):
            f.write("\t" + ", ".join("%d" % b for b in data[i:i + 20]) + ",\n")
        f.write("};\n\n#endif /* FONT_DATA_H */\n")
    print("wrote %s: %d glyphs, %d bytes of coverage" % (OUT, len(glyphs), len(data)))


if __name__ == "__main__":
    main()

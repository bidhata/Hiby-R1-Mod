int gb_font_width(const char *text, int scale) {
    if (scale < 1) scale = 1;
    return (int)strlen(text) * GB_FONT_ADVANCE * scale;
}

void gb_font_draw(gb_platform_t *platform, int x, int y, const char *text,
                  u32 color, int scale) {
    if (scale < 1) scale = 1;

    int cx = x;
    for (const u8 *p = (const u8 *)text; *p; p++) {
        u8 c = *p;
        if (c < 0x20 || c > 0x7E) c = ' ';
        const u8 *glyph = font5x7[c - 0x20];

        /* Glyph columns run left to right; each byte holds that column's
         * seven rows in its top bits. */
        for (int col = 0; col < GB_FONT_W; col++) {
            for (int row = 0; row < GB_FONT_H; row++) {
                if (!(glyph[col] & (0x80 >> row))) continue;
                gb_platform_fill_rect(platform,
                                      cx + col * scale, y + row * scale,
                                      scale, scale, color);
            }
        }
        cx += GB_FONT_ADVANCE * scale;
    }
}
